import andrewaylett from 'eslint-config-andrewaylett';
import nextPlugin from '@next/eslint-plugin-next';
import globals from 'globals';
import tseslint from 'typescript-eslint';

/**
 * Turns an error into a warning, and leaves anything else as it is. The UI
 * wasn't written to these rules, so each is a warning until the code is fixed
 * and the rule can be an error. Delete this when none are left.
 */
const warn = (setting) => {
  const [level, ...options] = Array.isArray(setting) ? setting : [setting];
  return level === 'error' || level === 2 ? ['warn', ...options] : setting;
};

const downgrade = (config) =>
  config.rules
    ? {
        ...config,
        rules: Object.fromEntries(
          Object.entries(config.rules).map(([name, setting]) => [
            name,
            warn(setting),
          ]),
        ),
      }
    : config;

export default tseslint
  .config(
    {
      // `lib/wasm` is generated by `pnpm ui wasm`; `out` and `.next` are builds.
      ignores: [
        '**/node_modules/*',
        '.next/*',
        'out/*',
        'test-results/*',
        'playwright-report/*',
        'lib/wasm/*',
        'next-env.d.ts',
      ],
    },
    {
      languageOptions: {
        parserOptions: {
          projectService: {
            allowDefaultProject: ['*.mjs', '*.mts'],
          },
        },
        globals: { ...globals.browser, ...globals.node },
      },
    },
    nextPlugin.configs.recommended,
    {
      files: ['**/*.ts', '**/*.tsx', '**/*.mts'],
      ...andrewaylett.configs.recommendedWithReactWithTypes,
    },
    andrewaylett.configs.recommendedWithReact,
    {
      settings: {
        react: { version: 'detect' },
        'import/resolver': { node: true },
      },
      rules: {
        curly: ['error', 'all'],
        'unicorn/filename-case': 'off',
        'unicorn/no-null': 'off',
        'unicorn/no-await-expression-member': 'off',
        '@typescript-eslint/restrict-template-expressions': [
          'error',
          { allowBoolean: true, allowNumber: true },
        ],
        '@typescript-eslint/no-inferrable-types': 'off',
        '@typescript-eslint/no-import-type-side-effects': 'error',
        'import/consistent-type-specifier-style': 'off',
        'unicorn/no-array-sort': 'off',
        'unicorn/no-array-reverse': 'off',
        'import/no-duplicates': ['error', { 'prefer-inline': true }],
        'import/no-extraneous-dependencies': 'error',
        'react/react-in-jsx-scope': 'off',
        'react/jsx-uses-react': 'off',
      },
    },
  )
  .map(downgrade);
